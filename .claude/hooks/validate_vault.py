#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Валидатор vault — формальные проверки регламента.

Запуск: python .claude/hooks/validate_vault.py
Выход: 0 — нарушений нет (предупреждения допустимы); 1 — есть нарушения.

Нарушения (валят коммит):
  1. Статус не из словаря (свой словарь для задачных и постоянных
     типов).
  2. Заметка «сделано» без хэша коммита в теле.
  3. У заметки-задачи нет секции «Как проверим».
  4. Маркер «⚠️ уточнить» в заметке, которая уже не «запланировано»
     (согласована) — маркеры снимаются до согласования.
  5. В шапке нет поля «тип» или «статус».

Предупреждения (не валят — честная ссылка-задел разрешена):
  - ссылка [[...]] на несуществующую заметку.

Пропускаются: файлы без YAML-шапки (README), шаблоны («Шаблон …»),
автоген (тип: автоген).
"""
import re
import sys
from pathlib import Path

# Консоль Windows по умолчанию не UTF-8 — переключаем потоки явно.
for _s in (sys.stdout, sys.stderr):
    if hasattr(_s, "reconfigure"):
        _s.reconfigure(encoding="utf-8")

КОРЕНЬ = Path(__file__).resolve().parents[2]
VAULT = КОРЕНЬ / "docs" / "vault"

ТИПЫ_ЗАДАЧ = {"задача", "баг"}
ТИПЫ_ПОСТОЯННЫЕ = {"модуль", "решение"}
# meta бывает и постоянным документом («действует» — Регламент), и
# разовым событием («сделано»); допустимы оба словаря.
ТИПЫ_СМЕШАННЫЕ = {"meta"}
СТАТУСЫ_ЗАДАЧ = {"запланировано", "в работе", "сделано", "заморожено"}
СТАТУСЫ_ПОСТОЯННЫХ = {"действует", "заменено"}

БЕЗ_ПРОВЕРКИ_ССЫЛОК = ("Шаблон", "Регламент", "README")

# Ссылки-плейсхолдеры из примеров в заметках — не считаются битыми.
ПРИМЕРЫ_ССЫЛОК = {"...", "…", "имя", "имя новой заметки", "ссылки", "ссылка"}

# Хэш коммита: 7-40 hex-символов, хотя бы одна буква a-f
# (иначе совпадают чистые числа вроде дат).
ХЭШ = re.compile(r"\b(?=[0-9a-f]*[a-f])[0-9a-f]{7,40}\b")


def шапка(текст):
    """Разбирает YAML-шапку. Возвращает (словарь | None, тело)."""
    if not текст.startswith("---"):
        return None, текст
    м = re.match(r"^---\s*\n(.*?)\n---\s*\n?", текст, re.S)
    if not м:
        return None, текст
    поля = {}
    for строка in м.group(1).splitlines():
        if ":" in строка:
            ключ, _, значение = строка.partition(":")
            поля[ключ.strip()] = значение.strip()
    return поля, текст[м.end() :]


def main():
    нарушения = []
    предупреждения = []
    файлы = sorted(VAULT.rglob("*.md"))
    имена = {f.stem for f in файлы}

    for f in файлы:
        имя = f.stem
        отн = f.relative_to(VAULT)
        if имя.startswith("Шаблон"):
            continue
        текст = f.read_text(encoding="utf-8")
        поля, тело = шапка(текст)
        if поля is None:
            continue  # README и прочие файлы без шапки
        тип = поля.get("тип", "")
        статус = поля.get("статус", "")
        if тип == "автоген":
            continue

        if not тип:
            нарушения.append(f"{отн}: в шапке нет поля «тип»")
        if not статус:
            нарушения.append(f"{отн}: в шапке нет поля «статус»")

        if тип in ТИПЫ_ЗАДАЧ:
            словарь = СТАТУСЫ_ЗАДАЧ
        elif тип in ТИПЫ_ПОСТОЯННЫЕ:
            словарь = СТАТУСЫ_ПОСТОЯННЫХ
        elif тип in ТИПЫ_СМЕШАННЫЕ:
            словарь = СТАТУСЫ_ЗАДАЧ | СТАТУСЫ_ПОСТОЯННЫХ
        else:
            словарь = СТАТУСЫ_ЗАДАЧ | СТАТУСЫ_ПОСТОЯННЫХ
            if тип:
                предупреждения.append(
                    f"{отн}: неизвестный тип «{тип}» — статус проверен "
                    f"по объединённому словарю"
                )
        if статус and статус not in словарь:
            нарушения.append(
                f"{отн}: статус «{статус}» не из словаря "
                f"({', '.join(sorted(словарь))})"
            )

        if статус == "сделано" and not ХЭШ.search(тело):
            нарушения.append(
                f"{отн}: статус «сделано», но в теле нет хэша коммита"
            )

        if тип in ТИПЫ_ЗАДАЧ and "## Как проверим" not in тело:
            нарушения.append(f"{отн}: нет секции «Как проверим»")

        # Маркер — отдельной строкой (в тексте-описании «⚠️ уточнить»
        # в кавычках внутри предложения маркером не считается).
        if re.search(r"^\s*(?:[-*>]\s*)*⚠️ уточнить", тело, re.M) and статус not in (
            "",
            "запланировано",
        ):
            нарушения.append(
                f"{отн}: неснятый маркер «⚠️ уточнить» при статусе "
                f"«{статус}» — маркеры снимаются до согласования"
            )

        if not имя.startswith(БЕЗ_ПРОВЕРКИ_ССЫЛОК):
            for ссылка in re.findall(r"\[\[([^\]]+)\]\]", тело):
                цель = ссылка.split("|")[0].split("#")[0]
                # Перенос строки внутри ссылки (заметки с wrap) и
                # цитатные «>» — нормализуем в один пробел.
                цель = " ".join(с for с in цель.split() if с != ">")
                if цель and цель not in ПРИМЕРЫ_ССЫЛОК and цель not in имена:
                    предупреждения.append(
                        f"{отн}: битая ссылка [[{цель}]] "
                        f"(допустимо как честный задел)"
                    )

    for п in предупреждения:
        print(f"⚠ {п}")
    for н in нарушения:
        print(f"✗ {н}")
    if нарушения:
        print(f"\nВалидатор vault: {len(нарушения)} нарушение(й).")
        return 1
    print(
        f"Валидатор vault: чисто "
        f"({len(файлы)} файлов, предупреждений: {len(предупреждения)})."
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())

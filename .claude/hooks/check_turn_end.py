#!/usr/bin/env python3
# -*- coding: utf-8 -*-
# reglament-plugin v1.4.3
"""Хук контроля незавершённых шагов (Stop — ассистент закончил ход).

Одна проверка: в фазе «заметка», пока согласования нет, ход не
заканчивается молча. Ассистент обязан либо задать карточку вопроса
(AskUserQuestion) с вариантом «Согласовано», либо — если
согласование ещё обсуждается — закончить ход конкретным вопросом.

Согласование ищется там же, где его ищет gate_edit.py: в
стенограмме сессии. Общая функция берётся импортом из gate_edit —
чтобы правило было записано в одном месте (оба файла лежат рядом,
в .claude/hooks/).

Защита от цикла — встроенная: stop_hook_active=true, когда ход уже
разворачивался хуком; после 8 блокировок подряд Claude Code
перебивает хук сам. Свой флаг в табло не заводим: он застрянет
выставленным, если сессия оборвётся посреди хода.

Выходы: 0 — пропустить ход; stdout с {"decision": "block"} —
вернуть ассистента, текст reason уйдёт ему как инструкция.
"""
import json
import os
import sys
from pathlib import Path

# Все потоки — в UTF-8 (stdin обязательно: харнесс шлёт JSON в UTF-8).
for _s in (sys.stdin, sys.stdout, sys.stderr):
    if hasattr(_s, "reconfigure"):
        _s.reconfigure(encoding="utf-8")

try:  # правило согласования живёт в gate_edit.py, дублировать нельзя
    from gate_edit import ВАРИАНТ_СОГЛАСИЯ, найти_согласование
except Exception:  # соседа нет — молчим, чтобы не блокировать зря
    ВАРИАНТ_СОГЛАСИЯ = None
    найти_согласование = None

КОРЕНЬ = Path(
    os.environ.get("CLAUDE_PROJECT_DIR") or Path(__file__).resolve().parents[2]
)
ТАБЛО = КОРЕНЬ / ".claude" / "task-state.json"
# Единственная фаза, в которой ждём согласования (словарь фаз: vault →
# заметка → согласовано → код → тесты → коммит → закрыто).
ФАЗА_ОЖИДАНИЯ = "заметка"


def пропустить():
    return 0


def вернуть(причина):
    """Блокировка завершения хода: reason уходит ассистенту."""
    print(json.dumps({"decision": "block", "reason": причина}, ensure_ascii=False))
    return 0


def main():
    if найти_согласование is None:
        return пропустить()
    try:
        данные = json.load(sys.stdin)
    except Exception:
        return пропустить()

    # Встроенный страж цикла: ход уже разворачивался — не мешаем.
    if данные.get("stop_hook_active") is True:
        return пропустить()

    if not ТАБЛО.exists():
        return пропустить()
    try:
        табло = json.loads(ТАБЛО.read_text(encoding="utf-8"))
    except Exception:
        return пропустить()

    задача = табло.get("задача")
    if not задача:
        return пропустить()
    # Малая форма идёт без карточки — там ждать нечего.
    if табло.get("форма") == "малая":
        return пропустить()
    if табло.get("фаза", "") != ФАЗА_ОЖИДАНИЯ:
        return пропустить()
    # Согласование уже есть — в этой сессии или в прошлой.
    if найти_согласование(данные.get("transcript_path"), задача):
        return пропустить()
    if табло.get("одобрено") is True and табло.get("одобрено_записью"):
        return пропустить()

    последнее = (данные.get("last_assistant_message") or "").rstrip()
    # Ход-вопрос: согласование ещё обсуждается, не мешаем.
    if последнее.endswith("?"):
        return пропустить()

    return вернуть(
        f"Задача «{задача}» в фазе «заметка», согласования нет, а ход "
        f"закончился без действия для пользователя. Если проект "
        f"заметки показан — задай карточку вопроса (инструмент "
        f"AskUserQuestion): в тексте вопроса название задачи "
        f"«{задача}», среди вариантов «{ВАРИАНТ_СОГЛАСИЯ}» и вариант "
        f"отказа. Клик по «{ВАРИАНТ_СОГЛАСИЯ}» и есть согласование — "
        f"работа продолжится тем же ходом, ждать и будить сессию не "
        f"нужно. Если заметка ещё не показана или обсуждается — "
        f"заверши ход конкретным вопросом пользователю."
    )


if __name__ == "__main__":
    sys.exit(main())

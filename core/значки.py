"""Набор значков разделов: список, подписи и подбор по названию.

Сами картинки нарисованы для проекта и лежат в шаблоне
`_значки.html` — здесь только их перечень (он же список выбора
в справочнике) и правило «какой значок подставить, если
пользователь не выбрал» (правила 2 и 6 заметки «Значки разделов»).

Набор закрытый: своих картинок пользователь не загружает. Так
экраны остаются в одном стиле, а система — без внешних файлов.
"""

# Ключ хранится в базе и подставляется в имя картинки (#и-машина),
# подпись видна в справочнике под плиткой выбора.
НАБОР = [
    ("машина", "машина"),
    ("дом", "дом"),
    ("участок", "участок"),
    ("семья", "семья"),
    ("деньги", "деньги"),
    ("здоровье", "здоровье"),
    ("учреждение", "учреждение"),
    ("вещи", "вещи"),
    ("животные", "животные"),
    ("работа", "работа"),
    ("учёба", "учёба"),
    ("ремонт", "ремонт"),
    ("поездки", "поездки"),
    ("быт", "быт"),
    ("техника", "техника"),
    ("спорт", "спорт"),
]

КЛЮЧИ = [ключ for ключ, _ in НАБОР]

# Подбор идёт сверху вниз, первое совпадение выигрывает: частные
# случаи стоят выше общих, иначе «Ремонт квартиры» стал бы «домом»,
# а «Школа» — «учреждением». Слова пишутся без «ё» — название
# приводится к тому же виду перед сравнением.
ПОДБОР = [
    (("ремонт", "инструм", "строй", "строит"), "ремонт"),
    (("учеб", "школ", "курс", "институт", "универ", "занят"), "учёба"),
    (("живот", "кот", "кош", "соба", "щен", "птиц"), "животные"),
    (("машин", "авто", "транспорт", "гараж", "мото", "шин"), "машина"),
    (("участ", "сад", "огород", "двор", "хозяйств", "дач", "теплиц"),
     "участок"),
    (("дом", "квартир", "жиль", "котел", "котёл"), "дом"),
    (("сем", "родн", "дет", "жена", "муж", "родител"), "семья"),
    (("финанс", "деньг", "банк", "налог", "страхов", "кредит"), "деньги"),
    (("здоров", "врач", "медиц", "зуб", "аптек", "анализ"), "здоровье"),
    (("обществ", "госуд", "муниципал", "собран", "депутат"), "учреждение"),
    (("работ", "офис", "бизнес", "служб", "заказчик"), "работа"),
    (("поезд", "путеш", "отпуск", "билет", "виза"), "поездки"),
    (("техник", "комп", "телефон", "гаджет", "электрон"), "техника"),
    (("спорт", "трениров", "бег", "фитнес", "велосип"), "спорт"),
    (("быт", "кух", "еда", "продукт", "готов", "уборк"), "быт"),
    (("вещ", "покуп", "заказ", "склад", "хран"), "вещи"),
]


def подобрать(название):
    """Какой значок подставить разделу с таким названием.

    Не угадали — пустая строка: раздел без значка выглядит как
    раньше, и это нормальный исход, а не ошибка.
    """
    низ = (название or "").lower().replace("ё", "е")
    for слова, ключ in ПОДБОР:
        if any(слово in низ for слово in слова):
            return ключ
    return ""
